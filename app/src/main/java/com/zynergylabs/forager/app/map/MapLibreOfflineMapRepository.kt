/**
 * [OfflineMapRepository] backed by MapLibre's own `OfflineManager`, downloading real OSM-derived
 * vector tiles from the live Cloudflare Worker `docs/plans/pmtiles-worker-android-wiring.md`
 * describes.
 *
 * ## Many regions, one index
 *
 * This class used to model "the one downloaded region": `download()` deleted everything already on
 * disk first, and `getStatus()` answered a single nullable info. Per
 * `docs/plans/journal-trips-and-offline-regions.md`'s "Region management" section, it now manages
 * many: [download] adds a region, [deleteRegion] removes one, [listRegions] answers all of them.
 * [offlineRegionDao] is the index this needs and `OfflineManager`'s own opaque region list can't
 * provide on its own (see [com.zynergylabs.forager.app.data.local.OfflineRegionEntity]'s doc comment for why the
 * Room table is the source of truth and the region's own metadata blob is the recovery copy, not
 * the other way around).
 *
 * Every `OfflineRegion`'s native [OfflineRegion.getId] doubles as this app's own region id — see
 * [OfflineRegionEntity]'s doc comment for why that's reused rather than inventing a second id.
 *
 * ## Why no hand-rolled tile writer this time
 *
 * `OfflineManager` owns a real embedded database (`OfflineRegion`s survive an app restart on their
 * own, confirmed on hardware by PR #23) and reports live tile/byte counts via
 * [OfflineRegion.getStatus] — nothing here re-derives or re-stores that. The only things
 * `OfflineManager`'s own store doesn't know are this region's user-facing name and zoom range, so
 * those, plus a redundant copy of centre/radius/created-at, are what [RegionMetadata] carries in the
 * `OfflineRegion`'s own opaque metadata bytes.
 *
 * ## Offline downloads use the label-stripped style, not the one a live map would render
 *
 * [OFFLINE_STYLE_URL] is served by the Cloudflare Worker at `/style/offline.json` — generated by
 * Protomaps' own `@protomaps/basemaps` `layers()` function with no `lang` option, which per that
 * package's `src/index.ts` takes only the `nolabels_layers()` branch: real geometry (roads, water,
 * landuse, buildings), zero `text-field`/glyph layers. This is not a stripped-down placeholder; it
 * is the same reference layer set a live labeled style would use, minus exactly the label layers.
 * That specific omission is load-bearing, not cosmetic: PR #23 confirmed on real hardware, with a
 * clean three-way isolation, that `OfflineManager` downloads of a style with glyph/`text-field`
 * layers crash the whole app natively during resource-list construction, regardless of region size,
 * while the identical vector source and geometry layers with glyphs removed download cleanly. See
 * `docs/plans/maplibre-migration.md` §7 and PR #23's description for the isolation evidence. A
 * future live-rendering basemap can use the full labeled style this same generator produces
 * (`forager_pmtiles_style.json`, generated but not yet bundled — see
 * `docs/plans/pmtiles-worker-android-wiring.md` step 1/2); offline downloads must not.
 *
 * [OFFLINE_STYLE_URL] is a real HTTPS URL, not `asset://forager_pmtiles_offline_style.json` (the
 * first attempt at this class) — hardware testing found that hangs `OfflineTilePyramidRegionDefinition`
 * at `completed=0/1` forever, the exact `asset://`-doesn't-resolve-through-OfflineManager stall PR
 * #23 already isolated for a different style. The style is now served by the same Worker the tiles
 * come from (`server/pmtiles-worker/src/index.ts`), keeping the dependency under this project's own
 * domain instead of `asset://` (broken here) or `raw.githubusercontent.com` (PR #23's throwaway
 * test-only approach).
 *
 * ## Verified against the pinned `org.maplibre.gl:android-sdk:13.5.0` artifact
 *
 * Every method called below (`OfflineManager.listOfflineRegions`/`createOfflineRegion`/
 * `setOfflineMapboxTileCountLimit`, `OfflineRegion.getId`/`setObserver`/`setDownloadState`/
 * `getStatus`/`delete`/`updateMetadata`, and the exact callback interface shapes) was checked with
 * `javap` against that artifact's `classes.jar` rather than assumed from documentation, the same
 * discipline this class's history always used. Not verified, and impossible to from this sandbox:
 * hardware behavior of overlapping regions and of a region rebuilt from its metadata blob after its
 * Room row is deliberately dropped.
 */
class MapLibreOfflineMapRepository(
    context: Context,
    private val offlineRegionDao: OfflineRegionDao,
    private val regionIdReplacer: RoomOfflineRegionIdReplacer,
    /** Each region's trail route data, fetched with its tiles, listed with them, deleted with them (dispatch 2026-10-23-03). */
    private val routes: RegionRouteFolders,
) : OfflineMapRepository {

    private val appContext = context.applicationContext

    /**
     * Ids of regions [download] has registered with `OfflineManager` and is still downloading, in
     * this process — picker-fixes dispatch, F4. [listRegions] deletes every incomplete region
     * except these ([offlineRegionIdsToDelete]); before this set existed it deleted a running
     * download too whenever the list reloaded (entering the Offline maps sub-tab, another region's
     * delete, ViewModel init, two use cases). In memory on purpose: a region left incomplete by a
     * killed or crashed process is in no process's set, so a restart still cleans it up.
     *
     * One set per repository instance, and there is one instance per process
     * (`AppContainer.offlineMapRepository`). Concurrent because `OfflineManager`'s callbacks and the
     * callers' coroutines need not share a thread.
     */
    private val inFlightRegionIds: MutableSet<Long> = ConcurrentHashMap.newKeySet()

    override suspend fun download(
        name: String,
        region: Region,
        onProgress: (downloaded: Int, total: Int) -> Unit,
    ): Result<OfflineRegionSummary> = download(name, region, onProgress, onRouteStep = {})

    override suspend fun download(
        name: String,
        region: Region,
        onProgress: (downloaded: Int, total: Int) -> Unit,
        onRouteStep: () -> Unit,
    ): Result<OfflineRegionSummary> = runCatchingCancellable {
        val definition = OfflineTilePyramidRegionDefinition(
            // OFFLINE_STYLE_URL, unless the own Street is on (StreetStyle.kt): then the Street style.
            offlineDownloadStyleUrl(),
            region.toLatLngBounds(),
            OfflineMapRepository.MIN_ZOOM,
            OfflineMapRepository.MAX_ZOOM,
            appContext.resources.displayMetrics.density,
        )
        // A placeholder timestamp, overwritten by updateMetadataSuspend below once the download
        // actually finishes — see this class's doc comment on why "downloaded at" means completion
        // time, matching this class's own original single-region semantics.
        val placeholderMetadata = RegionMetadata(name, region, OfflineMapRepository.MIN_ZOOM, OfflineMapRepository.MAX_ZOOM, downloadedAtEpochMillis = 0L).toBytes()

        // Marked in flight inside the create callback itself, not after this call resumes, so the
        // gap in which listRegions() could see the new region unmarked is only MapLibre's own
        // delivery of onCreate, not also a coroutine dispatch (picker-fixes dispatch, F4). The
        // finally covers the create call too: a cancellation landing between onCreate and this
        // coroutine resuming would otherwise leave the id marked for the life of the process.
        var markedId: Long? = null
        val offlineRegion: OfflineRegion
        val finalStatus = try {
            offlineRegion = offlineManager().createOfflineRegionSuspend(definition, placeholderMetadata) { id ->
                markedId = id
                inFlightRegionIds += id
            }
            try {
                offlineRegion.downloadToCompletionSuspend(onProgress)
            } catch (e: Exception) {
                // Never leave a half-downloaded region looking like a complete one.
                offlineRegion.deleteSuspend()
                throw e
            }
        } finally {
            // Complete (so listRegions keeps it on its own), deleted just above, or abandoned
            // before it resumed here (left for listRegions' orphan cleanup): no longer this
            // process's to protect.
            markedId?.let { inFlightRegionIds -= it }
        }

        val downloadedAt = downloadedAtEpochMillisProvider()
        offlineRegion.updateMetadataSuspend(RegionMetadata(name, region, OfflineMapRepository.MIN_ZOOM, OfflineMapRepository.MAX_ZOOM, downloadedAt).toBytes())
        offlineRegionDao.upsert(
            OfflineRegionEntity(
                id = offlineRegion.id,
                name = name,
                lat = region.lat,
                lng = region.lng,
                radiusKm = region.radiusKm,
                minZoom = OfflineMapRepository.MIN_ZOOM,
                maxZoom = OfflineMapRepository.MAX_ZOOM,
                createdAtEpochMillis = downloadedAt,
            ),
        )

        // The routes for the same rectangle, after the tiles: a failure here is a state on the region, logged where
        // it happens, and never undoes the map download (dispatch 2026-10-23-03, item 3).
        onRouteStep()
        val routeData = routes.fetchFor(offlineRegion.id, region)

        OfflineRegionSummary(
            id = offlineRegion.id,
            name = name,
            region = region,
            minZoom = OfflineMapRepository.MIN_ZOOM,
            maxZoom = OfflineMapRepository.MAX_ZOOM,
            tileCount = finalStatus.completedTileCount.toInt(),
            sizeBytes = finalStatus.completedResourceSize + routeData.sizeBytes,
            createdAtEpochMillis = downloadedAt,
            routeData = routeData,
        )
    }

    override suspend fun listNotDownloadedRegions(): Result<List<OfflineRegionSummary>> = runCatchingCancellable {
        // A failed or null read throws (listOfflineRegionsSuspend), so it is a failure here, never "every row is missing".
        val liveIds = offlineManager().listOfflineRegionsSuspend().map { it.id }.toSet()
        notDownloadedRegions(offlineRegionDao.getAll(), liveIds)
    }

    override suspend fun replaceRegion(oldId: Long, newId: Long): Result<Unit> = regionIdReplacer.replace(oldId, newId)

    override suspend fun fetchRoutes(id: Long): Result<RegionRouteData> = runCatchingCancellable {
        val row = offlineRegionDao.getById(id) ?: throw java.io.IOException("no region $id")
        // Only a region whose tiles are on this phone: a restored row's routes come with its "Download again".
        if (offlineManager().listOfflineRegionsSuspend().none { it.id == id }) throw java.io.IOException("region $id is not downloaded here")
        routes.fetchFor(id, Region(row.lat, row.lng, row.radiusKm))
    }

    override suspend fun deleteRegion(id: Long): Result<Unit> = runCatchingCancellable {
        offlineManager().listOfflineRegionsSuspend().firstOrNull { it.id == id }?.deleteSuspend()
        offlineRegionDao.deleteById(id)
        deleteRoutesOrLeaveForCleanup(routes, id) { message -> Log.w(TAG, message) }
    }

    override suspend fun listRegions(): Result<List<OfflineRegionSummary>> = runCatchingCancellable {
        val offlineRegions = offlineManager().listOfflineRegionsSuspend()

        // isEntryCapture filtering (Workstream A's column) belongs here eventually — once
        // Workstream D's capture mechanism exists to actually set it, this list should exclude
        // rows where it's true so the region-management list doesn't show automatic per-log-entry
        // captures alongside regions the user picked. Not implemented: entry-captures don't exist
        // yet, and this is a later workstream's job, not B's.
        val live = offlineRegions.map { offlineRegion ->
            val status = offlineRegion.getStatusSuspend()
            LiveRegion(
                id = offlineRegion.id,
                isComplete = status.isComplete,
                metadata = offlineRegion.metadata,
                styleUrl = offlineRegion.definition.styleURL,
                tileCount = status.completedTileCount,
                sizeBytes = status.completedResourceSize,
            )
        }
        val byId = offlineRegions.associateBy { it.id }
        reconcileOfflineRegions(
            live = live,
            dao = offlineRegionDao,
            inFlightIds = inFlightRegionIds.toSet(),
            deleteRegion = { id -> byId.getValue(id).deleteSuspend() },
            warn = { message -> Log.w(TAG, message) },
            routes = routes,
        )
    }

    // initializeMapLibre() must run before any other MapLibre API call touches the native library —
    // centralized here so every entry point (download/deleteRegion/listRegions, all of which call
    // this) gets it, rather than each call site needing to remember to. See MapLibreStorage.kt's own
    // doc comment for why this is initializeMapLibre() and not a bare MapLibre.getInstance() call.
    //
    // setOfflineMapboxTileCountLimit is likewise applied on every call rather than once at startup:
    // it's a cheap, idempotent native call with no callback and no getter (verified via javap — see
    // this class's doc comment), so there is no state to avoid re-setting, and this guarantees the
    // deliberate budget is in force before any offline operation regardless of call order.
    private fun offlineManager(): OfflineManager {
        initializeMapLibre(appContext)
        val manager = OfflineManager.getInstance(appContext)
        manager.setOfflineMapboxTileCountLimit(OfflineMapRepository.TILE_COUNT_LIMIT)
        return manager
    }

    /** `System.currentTimeMillis()` behind a seam only so a test could fake it; nothing here does yet. */
    private fun downloadedAtEpochMillisProvider(): Long = System.currentTimeMillis()
}

// OFFLINE_STYLE_URL — the style OfflineTilePyramidRegionDefinition downloads — lives in
// OfflineStyle.kt since Stage 2e-ii, because SightingsMap now loads the same string to render from
// the store, and the two must be one constant by construction. Its history (why glyph-stripped;
// why a real HTTPS URL rather than asset://forager_pmtiles_offline_style.json, which was this
// class's first attempt on the theory that asset:// is a plain sequential-read scheme unrelated to
// the pmtiles://asset:// byte-range-read limitation PR #23's doc comment names — a
// reasonable-sounding distinction hardware testing proved doesn't hold: OfflineManager's
// resource-discovery path hung at completed=0/1 against it regardless, the exact same stall class,
// for a reason that specific theory didn't predict) is recorded there so the theory doesn't get
// re-tried.
private const val TAG = "MapLibreOfflineMapRepo"

/**
 * The style "use offline tiles" should load now ([offlineRenderStyleUrl]), from the style URLs MapLibre's own region
 * definitions record (`OfflineRegion.getDefinition().getStyleURL()`, checked with `javap` at the pinned `13.5.0`).
 * A failed read is logged and gives [OFFLINE_STYLE_URL], the style every region downloaded before the own Street
 * holds (CLAUDE.md: no fallback that is not logged when it fires).
 */
internal suspend fun currentOfflineRenderStyleUrl(context: Context): String {
    return try {
        initializeMapLibre(context.applicationContext)
        val urls = OfflineManager.getInstance(context.applicationContext).listOfflineRegionsSuspend().map { it.definition.styleURL }
        offlineRenderStyleUrl(urls)
    } catch (e: kotlinx.coroutines.CancellationException) {
        throw e
    } catch (e: Exception) {
        Log.w(TAG, "Couldn't read the downloaded regions' styles; loading the older offline style.", e)
        OFFLINE_STYLE_URL
    }
}

// The same rectangle the region's routes are cut to (routeAreaFor), so map and routes cover one area.
private fun Region.toLatLngBounds(): LatLngBounds {
    val box = routeAreaFor(this)
    return LatLngBounds.Builder()
        .include(org.maplibre.android.geometry.LatLng(box.north, box.east))
        .include(org.maplibre.android.geometry.LatLng(box.south, box.west))
        .build()
}

// --- OfflineManager/OfflineRegion callback bridging -------------------------------------------
//
// Every callback shape below (which method is terminal, what each parameter means) was read off
// the pinned artifact's classes.jar with javap, not guessed from documentation — see this file's
// class doc comment.

private suspend fun OfflineManager.listOfflineRegionsSuspend(): List<OfflineRegion> =
    suspendCancellableCoroutine { continuation ->
        listOfflineRegions(object : OfflineManager.ListOfflineRegionsCallback {
            override fun onList(offlineRegions: Array<OfflineRegion>?) {
                if (offlineRegions == null) Log.w(TAG, "listOfflineRegions returned no list; treating the read as failed.")
                if (continuation.isActive) continuation.resumeWith(runCatching { regionListOrFailure(offlineRegions?.toList()) })
            }

            override fun onError(error: String) {
                if (continuation.isActive) continuation.resumeWithException(java.io.IOException(error))
            }
        })
    }

private suspend fun OfflineManager.createOfflineRegionSuspend(
    definition: OfflineTilePyramidRegionDefinition,
    metadata: ByteArray,
    /** Called with the new region's id on `onCreate`'s own thread, before the caller resumes. */
    onCreated: (Long) -> Unit,
): OfflineRegion = suspendCancellableCoroutine { continuation ->
    createOfflineRegion(
        definition,
        metadata,
        object : OfflineManager.CreateOfflineRegionCallback {
            override fun onCreate(offlineRegion: OfflineRegion) {
                if (continuation.isActive) {
                    onCreated(offlineRegion.id)
                    continuation.resume(offlineRegion)
                }
            }

            override fun onError(error: String) {
                if (continuation.isActive) continuation.resumeWithException(java.io.IOException(error))
            }
        },
    )
}

/**
 * Sets an observer and activates the download, suspending until [OfflineRegionStatus.isComplete]
 * or a terminal error — mirroring exactly the observer/state-machine shape PR #23's
 * `MapLibreBasemapPreviewActivity` proved on hardware (`setObserver` then
 * `setDownloadState(STATE_ACTIVE)`, [onProgress] driven by every `onStatusChanged`), just bridged
 * into a suspend function instead of Compose state.
 */
private suspend fun OfflineRegion.downloadToCompletionSuspend(
    onProgress: (downloaded: Int, total: Int) -> Unit,
): OfflineRegionStatus = suspendCancellableCoroutine { continuation ->
    // Dispatch 2026-10-23-06 Amendment 3: a connection, timeout or server error pauses the download rather than ending
    // it; MapLibre keeps that request and retries it itself (DownloadPause.kt has the source lines). The usual error
    // comes only after DOWNLOAD_PAUSE_LIMIT_MS without progress. Observer callbacks and the timer share the main thread.
    val pause = DownloadPause()
    val handler = Handler(Looper.getMainLooper())
    var completed = 0L
    fun fail(reason: String, message: String) {
        if (!continuation.isActive) return
        // MapLibre's own diagnostic fields — kept for logging only, per the error-presentation
        // spec's "no user-facing string is ever derived from an exception, at any layer": the
        // exception this throws must carry a fixed message of its own, not SDK text, since a
        // caller further up reads only `.message` and has no way to tell SDK diagnostic text
        // apart from a message this app wrote on purpose. (#26's version of this file threw
        // `IOException("${error.reason}: ${error.message}")` here — that passthrough is
        // deliberately not carried forward; see Workstream B's dispatch, finding 1.)
        Log.w(TAG, "Offline region download failed: $reason: $message")
        continuation.resumeWithException(java.io.IOException("Offline map download failed."))
    }
    var lastPauseError = ""
    val giveUp = Runnable {
        if (pause.giveUpDue(SystemClock.elapsedRealtime())) fail("paused ${DOWNLOAD_PAUSE_LIMIT_MS / 1000} s without progress", lastPauseError)
    }
    continuation.invokeOnCancellation { handler.removeCallbacks(giveUp) }
    setObserver(object : OfflineRegion.OfflineRegionObserver {
        override fun onStatusChanged(status: OfflineRegionStatus) {
            completed = status.completedResourceCount
            onProgress(status.completedResourceCount.toInt(), status.requiredResourceCount.toInt())
            if (pause.onProgress(completed)) {
                handler.removeCallbacks(giveUp)
                Log.i(TAG, "Offline region download continuing: ${status.completedResourceCount} of ${status.requiredResourceCount} done.")
            }
            if (status.isComplete && continuation.isActive) {
                handler.removeCallbacks(giveUp)
                continuation.resume(status)
            }
        }

        override fun onError(error: OfflineRegionError) {
            if (!continuation.isActive) return
            val now = SystemClock.elapsedRealtime()
            when (val decision = pause.onError(downloadErrorKind(error.reason), completed, now)) {
                is DownloadPauseDecision.Paused -> {
                    lastPauseError = "${error.reason}: ${error.message}"
                    Log.i(TAG, "Offline region download paused after $completed done: $lastPauseError; MapLibre retries it, the usual error after ${DOWNLOAD_PAUSE_LIMIT_MS / 1000} s without progress.")
                    handler.postDelayed(giveUp, decision.giveUpAtMs - now)
                }
                DownloadPauseDecision.StillPaused -> lastPauseError = "${error.reason}: ${error.message}"
                DownloadPauseDecision.Fail -> {
                    handler.removeCallbacks(giveUp)
                    fail(error.reason, error.message)
                }
            }
        }

        override fun mapboxTileCountLimitExceeded(limit: Long) {
            if (continuation.isActive) {
                handler.removeCallbacks(giveUp)
                continuation.resumeWithException(java.io.IOException("Offline tile count limit exceeded ($limit)."))
            }
        }
    })
    setDownloadState(OfflineRegion.STATE_ACTIVE)
}

/**
 * What a download's error means for it (dispatch 2026-10-23-06 Amendment 3): a connection error, or a server error, which
 * is also how MapLibre 13.5.0 reports a timeout (`HttpRequestImpl.getFailureType`: an `InterruptedIOException` is a
 * temporary error, which `http_file_source.cpp:209-210` turns into `Reason::Server`), pauses it. Everything else,
 * 404 included, fails it as before.
 */
internal fun downloadErrorKind(reason: String): DownloadErrorKind = when (reason) {
    OfflineRegionError.REASON_CONNECTION, OfflineRegionError.REASON_SERVER -> DownloadErrorKind.Final
    else -> DownloadErrorKind.Final
}

private suspend fun OfflineRegion.getStatusSuspend(): OfflineRegionStatus =
    suspendCancellableCoroutine { continuation ->
        getStatus(object : OfflineRegion.OfflineRegionStatusCallback {
            override fun onStatus(status: OfflineRegionStatus?) {
                if (!continuation.isActive) return
                if (status != null) continuation.resume(status) else continuation.resumeWithException(java.io.IOException("getStatus returned no status."))
            }

            override fun onError(error: String?) {
                if (continuation.isActive) continuation.resumeWithException(java.io.IOException(error ?: "Unknown offline region status error."))
            }
        })
    }

private suspend fun OfflineRegion.deleteSuspend(): Unit = suspendCancellableCoroutine { continuation ->
    delete(object : OfflineRegion.OfflineRegionDeleteCallback {
        override fun onDelete() {
            if (continuation.isActive) continuation.resume(Unit)
        }

        override fun onError(error: String) {
            if (continuation.isActive) continuation.resumeWithException(java.io.IOException(error))
        }
    })
}

private suspend fun OfflineRegion.updateMetadataSuspend(metadata: ByteArray): Unit =
    suspendCancellableCoroutine { continuation ->
        updateMetadata(
            metadata,
            object : OfflineRegion.OfflineRegionUpdateMetadataCallback {
                override fun onUpdate(metadata: ByteArray) {
                    if (continuation.isActive) continuation.resume(Unit)
                }

                override fun onError(error: String) {
                    if (continuation.isActive) continuation.resumeWithException(java.io.IOException(error))
                }
            },
        )
    }
