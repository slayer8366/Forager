package com.zynergylabs.forager.app.map

import java.io.File
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Forager Trail Map's offline-style rules (dispatch 2026-10-18-05 Part 2; RECORD -1294, -1300) since the release switch
 * went (dispatch 2026-10-22-01, RECORD -1554, -1556): downloads are Trail Map only, whatever map type is showing.
 */
class TrailStyleTest {

    /**
     * The Trail Map style the app loads, as the Worker bundles and serves it at /style/trail-v4.json (dispatch 2026-11-03-05
     * D1; street-v4.json, the same style, before it), generated by map-style/generate-trail.mjs.
     */
    private val servedStyle = Json.parseToJsonElement(File("../server/pmtiles-worker/src/trail-style-v4.json").readText()).jsonObject

    /** Trail Map v3, still served frozen for the regions downloaded against it. */
    private val v3Style = Json.parseToJsonElement(File("../server/pmtiles-worker/src/street-style-v3.json").readText()).jsonObject

    @Test
    fun `new downloads are made in Forager Trail Map's style`() {
        // -1554: "Offline downloads → Trail Map only; no OpenStreetMap tiles are ever stored".
        assertEquals(TRAIL_STYLE_URL, offlineDownloadStyleUrl())
    }

    @Test
    fun `the offline map keeps the old style until some region holds Trail Map's`() {
        assertEquals("only older regions", OFFLINE_STYLE_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, OFFLINE_STYLE_URL)))
        assertEquals("no regions", OFFLINE_STYLE_URL, offlineRenderStyleUrl(emptyList()))
        assertEquals("a definition naming no URL", OFFLINE_STYLE_URL, offlineRenderStyleUrl(listOf(null)))
        assertEquals("one Trail Map region", TRAIL_STYLE_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, TRAIL_STYLE_URL)))
    }

    @Test
    fun `a phone holding v3 regions and no v4 one loads v3, the style they hold, and any v4 region wins`() {
        // The switch to v4 (dispatch 2026-11-01-coder-11 step (d)): v4, then v3, then v2, then v1, then the offline style.
        assertEquals("only v3 regions", TRAIL_STYLE_V3_URL, offlineRenderStyleUrl(listOf(TRAIL_STYLE_V3_URL, TRAIL_STYLE_V3_URL)))
        assertEquals("v3, v2, v1 and older regions", TRAIL_STYLE_V3_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, TRAIL_STYLE_V1_URL, TRAIL_STYLE_V3_URL, TRAIL_STYLE_V2_URL, null)))
        assertEquals("v3 and v4 regions", TRAIL_STYLE_URL, offlineRenderStyleUrl(listOf(TRAIL_STYLE_V3_URL, TRAIL_STYLE_URL)))
        assertEquals("all five", TRAIL_STYLE_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, TRAIL_STYLE_V1_URL, TRAIL_STYLE_URL, TRAIL_STYLE_V2_URL, TRAIL_STYLE_V3_URL)))
    }

    @Test
    fun `a phone holding v2 regions and no v3 one loads v2, the style they hold, and any v3 region wins`() {
        // Dispatch 2026-10-26-21: v3, then v2, then v1, then the offline style, as -1561's Amendment 1 put v1 after v2.
        assertEquals("only v2 regions", TRAIL_STYLE_V2_URL, offlineRenderStyleUrl(listOf(TRAIL_STYLE_V2_URL, TRAIL_STYLE_V2_URL)))
        assertEquals("v2, v1 and older regions", TRAIL_STYLE_V2_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, TRAIL_STYLE_V1_URL, TRAIL_STYLE_V2_URL, null)))
        assertEquals("v2 and v3 regions", TRAIL_STYLE_V3_URL, offlineRenderStyleUrl(listOf(TRAIL_STYLE_V2_URL, TRAIL_STYLE_V3_URL)))
        assertEquals("all four", TRAIL_STYLE_V3_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, TRAIL_STYLE_V1_URL, TRAIL_STYLE_V3_URL, TRAIL_STYLE_V2_URL)))
    }

    @Test
    fun `a phone holding only regions downloaded before v2 loads v1, the style they hold`() {
        // Dispatch 2026-10-22-03 Amendment 1: v2, then v1, then the offline style. Loading v2 or the offline style here
        // would load a style no region holds, and the offline map would not draw.
        assertEquals("only v1 regions", TRAIL_STYLE_V1_URL, offlineRenderStyleUrl(listOf(TRAIL_STYLE_V1_URL, TRAIL_STYLE_V1_URL)))
        assertEquals("v1 and older regions", TRAIL_STYLE_V1_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, TRAIL_STYLE_V1_URL, null)))
        assertEquals("v1 and v2 regions", TRAIL_STYLE_V2_URL, offlineRenderStyleUrl(listOf(TRAIL_STYLE_V1_URL, TRAIL_STYLE_V2_URL)))
        assertEquals("all three", TRAIL_STYLE_V3_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, TRAIL_STYLE_V3_URL, TRAIL_STYLE_V1_URL)))
    }

    @Test
    fun `the older-style notice shows only on a downloaded region built against another style`() {
        assertTrue(regionHasOlderMapStyle(OFFLINE_STYLE_URL, isDownloaded = true))
        // RECORD -1561, the owner: "The existing notice" for regions downloaded under v1.
        assertTrue("a v1 region is older", regionHasOlderMapStyle(TRAIL_STYLE_V1_URL, isDownloaded = true))
        // Dispatch 2026-10-26-21: "v2 regions keep v2 and show the existing older-style notice".
        assertTrue("a v2 region is older", regionHasOlderMapStyle(TRAIL_STYLE_V2_URL, isDownloaded = true))
        // The switch to v4: a v3 region keeps v3 and shows the same notice.
        assertTrue("a v3 region is older", regionHasOlderMapStyle(TRAIL_STYLE_V3_URL, isDownloaded = true))
        assertFalse("a Trail Map region is current", regionHasOlderMapStyle(TRAIL_STYLE_URL, isDownloaded = true))
        assertFalse("not downloaded on this phone", regionHasOlderMapStyle(OFFLINE_STYLE_URL, isDownloaded = false))
        assertFalse("an unknown style is never guessed old", regionHasOlderMapStyle(null, isDownloaded = true))
    }

    // Dispatch 2026-11-03-05 D1 (RECORD -2000): the owner, "Add trail-v4 now"; the planner, street-v4 and trail-v4 are one
    // style, so no region shows a false "Older map style" notice ("Don't make me think").
    @Test
    fun `the app loads trail-v4, and street-v4 is the same style under its old address`() {
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/style/trail-v4.json", TRAIL_STYLE_URL)
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/style/street-v4.json", TRAIL_STYLE_V4_STREET_URL)
        assertEquals(
            listOf(TRAIL_STYLE_URL, TRAIL_STYLE_V4_STREET_URL, TRAIL_STYLE_V3_URL, TRAIL_STYLE_V2_URL, TRAIL_STYLE_V1_URL),
            TRAIL_STYLE_URLS,
        )
        assertEquals("downloads are made in trail-v4", TRAIL_STYLE_URL, offlineDownloadStyleUrl())
    }

    @Test
    fun `a region downloaded against street-v4 shows no older-style notice, as a trail-v4 one shows none`() {
        assertFalse("street-v4 is today's style", regionHasOlderMapStyle(TRAIL_STYLE_V4_STREET_URL, isDownloaded = true))
        assertFalse("trail-v4", regionHasOlderMapStyle(TRAIL_STYLE_URL, isDownloaded = true))
        assertTrue("v3 is still older", regionHasOlderMapStyle(TRAIL_STYLE_V3_URL, isDownloaded = true))
    }

    @Test
    fun `the offline map loads trail-v4 when a region holds it, street-v4 when only that does, and each wins over v3`() {
        assertEquals("only street-v4 regions", TRAIL_STYLE_V4_STREET_URL, offlineRenderStyleUrl(listOf(TRAIL_STYLE_V4_STREET_URL)))
        assertEquals("street-v4 and v3", TRAIL_STYLE_V4_STREET_URL, offlineRenderStyleUrl(listOf(TRAIL_STYLE_V3_URL, TRAIL_STYLE_V4_STREET_URL)))
        assertEquals("trail-v4 and street-v4", TRAIL_STYLE_URL, offlineRenderStyleUrl(listOf(TRAIL_STYLE_V4_STREET_URL, TRAIL_STYLE_URL)))
    }

    @Test
    fun `the notice reads as accepted`() {
        // Dispatch 2026-11-04-09 A8, RECORD -2112, the owner: "Look and hill shading (Recommended)".
        assertEquals("Older map style. Download again for the new look and hill shading.", OLDER_MAP_STYLE_NOTICE)
    }

    @Test
    fun `the Trail Map style URLs are the Worker's routes, on the same host as the offline style`() {
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/style/trail-v4.json", TRAIL_STYLE_URL)
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/style/street-v3.json", TRAIL_STYLE_V3_URL)
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/style/street-v2.json", TRAIL_STYLE_V2_URL)
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/style/street-v1.json", TRAIL_STYLE_V1_URL)
        assertEquals(OFFLINE_STYLE_URL.substringBefore("/style/"), TRAIL_STYLE_URL.substringBefore("/style/"))
    }

    @Test
    fun `the app's icon list is sprite v5's, as v3 records it, and v4 records it with sprite v6's three patterns`() {
        val v3Icons = v3Style.getValue("metadata").jsonObject.getValue("forager:sprite-icons").jsonArray.map { it.jsonPrimitive.content }
        assertEquals(v3Icons, TRAIL_SPRITE_ICON_NAMES)
        val v4Icons = servedStyle.getValue("metadata").jsonObject.getValue("forager:sprite-icons").jsonArray.map { it.jsonPrimitive.content }
        assertEquals((TRAIL_SPRITE_ICON_NAMES + listOf("nursery_dots", "orchard_dots", "vineyard_rows")).sorted(), v4Icons)
    }

    @Test
    fun `the served style is v4 on sprite v6, v3 and v2 are on sprite v5, and v1 is still served as it was`() {
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/sprites/v6/light", servedStyle.getValue("sprite").jsonPrimitive.content)
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/sprites/v5/light", v3Style.getValue("sprite").jsonPrimitive.content)
        val v2 = Json.parseToJsonElement(File("../server/pmtiles-worker/src/street-style-v2.json").readText()).jsonObject
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/sprites/v5/light", v2.getValue("sprite").jsonPrimitive.content)
        // v2's icon list is v3's, so a v2 region's icons still invert.
        assertEquals(TRAIL_SPRITE_ICON_NAMES, v2.getValue("metadata").jsonObject.getValue("forager:sprite-icons").jsonArray.map { it.jsonPrimitive.content })
        val v1 = Json.parseToJsonElement(File("../server/pmtiles-worker/src/street-style-v1.json").readText()).jsonObject
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/sprites/v4/light", v1.getValue("sprite").jsonPrimitive.content)
        // v1's icon list is v4's 53, every one of them still on the app's list, so a v1 region's icons still invert.
        val v1Icons = v1.getValue("metadata").jsonObject.getValue("forager:sprite-icons").jsonArray.map { it.jsonPrimitive.content }
        assertEquals(53, v1Icons.size)
        assertEquals(emptyList<String>(), v1Icons.filter { it !in TRAIL_SPRITE_ICON_NAMES })
    }

    @Test
    fun `the Protomaps credit names Forager Trail Map`() {
        // RECORD -1556: credit text that names our map says "Forager Trail Map".
        assertEquals("Protomaps (Forager Trail Map and offline maps)", com.zynergylabs.forager.app.ui.credits.PROTOMAPS_CREDIT_TEXT)
    }

    @Test
    fun `the zoom limit is the owner's 18`() {
        assertEquals(18, TRAIL_STYLE_MAX_ZOOM)
    }
}
