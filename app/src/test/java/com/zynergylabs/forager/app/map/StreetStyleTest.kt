package com.zynergylabs.forager.app.map

import java.io.File
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Forager Trail Map's offline-style rules (dispatch 2026-10-18-05 Part 2; RECORD -1294, -1300) since the release switch
 * went (dispatch 2026-10-22-01, RECORD -1554, -1556): downloads are Trail Map only, whatever map type is showing.
 */
class StreetStyleTest {

    /** The Street style the Worker bundles and serves at /style/street-v2.json, generated by map-style/generate-street.mjs. */
    private val servedStyle = Json.parseToJsonElement(File("../server/pmtiles-worker/src/street-style-v2.json").readText()).jsonObject

    @Test
    fun `new downloads are made in Forager Trail Map's style`() {
        // -1554: "Offline downloads → Trail Map only; no OpenStreetMap tiles are ever stored".
        assertEquals(STREET_STYLE_URL, offlineDownloadStyleUrl())
    }

    @Test
    fun `the offline map keeps the old style until some region holds Trail Map's`() {
        assertEquals("only older regions", OFFLINE_STYLE_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, OFFLINE_STYLE_URL)))
        assertEquals("no regions", OFFLINE_STYLE_URL, offlineRenderStyleUrl(emptyList()))
        assertEquals("a definition naming no URL", OFFLINE_STYLE_URL, offlineRenderStyleUrl(listOf(null)))
        assertEquals("one Trail Map region", STREET_STYLE_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, STREET_STYLE_URL)))
    }

    @Test
    fun `a phone holding only regions downloaded before v2 loads v1, the style they hold`() {
        // Dispatch 2026-10-22-03 Amendment 1: v2, then v1, then the offline style. Loading v2 or the offline style here
        // would load a style no region holds, and the offline map would not draw.
        assertEquals("only v1 regions", STREET_STYLE_V1_URL, offlineRenderStyleUrl(listOf(STREET_STYLE_V1_URL, STREET_STYLE_V1_URL)))
        assertEquals("v1 and older regions", STREET_STYLE_V1_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, STREET_STYLE_V1_URL, null)))
        assertEquals("v1 and v2 regions", STREET_STYLE_URL, offlineRenderStyleUrl(listOf(STREET_STYLE_V1_URL, STREET_STYLE_URL)))
        assertEquals("all three", STREET_STYLE_URL, offlineRenderStyleUrl(listOf(OFFLINE_STYLE_URL, STREET_STYLE_URL, STREET_STYLE_V1_URL)))
    }

    @Test
    fun `the older-style notice shows only on a downloaded region built against another style`() {
        assertTrue(regionHasOlderMapStyle(OFFLINE_STYLE_URL, isDownloaded = true))
        // RECORD -1561, the owner: "The existing notice" for regions downloaded under v1.
        assertTrue("a v1 region is older", regionHasOlderMapStyle(STREET_STYLE_V1_URL, isDownloaded = true))
        assertFalse("a Trail Map region is current", regionHasOlderMapStyle(STREET_STYLE_URL, isDownloaded = true))
        assertFalse("not downloaded on this phone", regionHasOlderMapStyle(OFFLINE_STYLE_URL, isDownloaded = false))
        assertFalse("an unknown style is never guessed old", regionHasOlderMapStyle(null, isDownloaded = true))
    }

    @Test
    fun `the notice reads as accepted`() {
        assertEquals("Older map style. Download again to update.", OLDER_MAP_STYLE_NOTICE)
    }

    @Test
    fun `the Street style URL is the Worker's route, on the same host as the offline style`() {
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/style/street-v2.json", STREET_STYLE_URL)
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/style/street-v1.json", STREET_STYLE_V1_URL)
        assertEquals(OFFLINE_STYLE_URL.substringBefore("/style/"), STREET_STYLE_URL.substringBefore("/style/"))
        assertEquals(listOf(STREET_STYLE_URL, STREET_STYLE_V1_URL), STREET_STYLE_URLS)
    }

    @Test
    fun `the app's icon list is the sprite's, as the served style records it`() {
        val recorded = servedStyle.getValue("metadata").jsonObject.getValue("forager:sprite-icons").jsonArray.map { it.jsonPrimitive.content }
        assertEquals(recorded, STREET_SPRITE_ICON_NAMES)
    }

    @Test
    fun `the served style is v2 on sprite v5, and v1 is still served as it was`() {
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/sprites/v5/light", servedStyle.getValue("sprite").jsonPrimitive.content)
        val v1 = Json.parseToJsonElement(File("../server/pmtiles-worker/src/street-style-v1.json").readText()).jsonObject
        assertEquals("https://forager-pmtiles.brandonlee1-894.workers.dev/sprites/v4/light", v1.getValue("sprite").jsonPrimitive.content)
        // v1's icon list is v4's 53, every one of them still on the app's list, so a v1 region's icons still invert.
        val v1Icons = v1.getValue("metadata").jsonObject.getValue("forager:sprite-icons").jsonArray.map { it.jsonPrimitive.content }
        assertEquals(53, v1Icons.size)
        assertEquals(emptyList<String>(), v1Icons.filter { it !in STREET_SPRITE_ICON_NAMES })
    }

    @Test
    fun `the Protomaps credit names Forager Trail Map`() {
        // RECORD -1556: credit text that names our map says "Forager Trail Map".
        assertEquals("Protomaps (Forager Trail Map and offline maps)", com.zynergylabs.forager.app.ui.credits.PROTOMAPS_CREDIT_TEXT)
    }

    @Test
    fun `the zoom limit is the owner's 18`() {
        assertEquals(18, STREET_STYLE_MAX_ZOOM)
    }
}
